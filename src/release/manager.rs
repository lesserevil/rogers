#[cfg(test)]
mod tests {
    use super::*;
    use crate::backport::completeness::BackportBeadInfo;

    fn make_result(branch: &str, critical: usize, critical_closed: usize) -> CompletenessResult {
        let beads: Vec<_> = (0..critical)
            .map(|i| BackportBeadInfo {
                id: format!("bp-{}", i),
                target_branch: branch.to_string(),
                is_critical: true,
                is_closed: i < critical_closed,
                source_sha: Some("abc123".to_string()),
                source_pr: Some(42),
            })
            .collect();

        let remaining: Vec<_> = beads.iter().filter(|b| !b.is_closed).cloned().collect();

        CompletenessResult {
            release_branch: branch.to_string(),
            total_beads: critical,
            critical_beads: critical,
            critical_closed,
            non_critical_closed: 0,
            is_complete: critical_closed == critical,
            remaining_beads: remaining,
        }
    }

    #[test]
    fn test_release_suggestion_title_format() {
        let title = format!("Release Suggestion: {}", "release/1.x");
        assert_eq!(title, "Release Suggestion: release/1.x");
    }

    #[test]
    fn test_build_description_with_backports() {
        let result = make_result("release/1.x", 3, 3);
        let deps = vec!["bp-0".to_string(), "bp-1".to_string(), "bp-2".to_string()];
        let desc = build_release_suggestion_description(&result, &deps);

        assert!(desc.contains("Plan: plans/backport-plan.md"));
        assert!(desc.contains("Plan: plans/release-management-plan.md"));
        assert!(desc.contains("release/1.x"));
        assert!(desc.contains("All critical backports"));
        assert!(desc.contains("- bp-0"));
        assert!(desc.contains("- bp-1"));
        assert!(desc.contains("- bp-2"));
        assert!(desc.contains("Critical backports: 3"));
        assert!(desc.contains("Next Steps"));
    }

    #[test]
    fn test_build_description_without_backports() {
        let result = make_result("release/2.x", 0, 0);
        let desc = build_release_suggestion_description(&result, &[]);

        assert!(desc.contains("release/2.x"));
        assert!(desc.contains("(none)"));
        assert!(desc.contains("Critical backports: 0"));
    }

    #[test]
    fn test_release_suggestion_result_structure() {
        let result = ReleaseSuggestionResult {
            release_branch: "release/1.x".to_string(),
            bead_id: "suggest-1".to_string(),
            backports_included: 3,
            success: true,
            errors: vec![],
        };

        assert_eq!(result.release_branch, "release/1.x");
        assert_eq!(result.bead_id, "suggest-1");
        assert_eq!(result.backports_included, 3);
        assert!(result.success);
        assert!(result.errors.is_empty());
    }

    #[test]
    fn test_release_suggestion_result_with_errors() {
        let result = ReleaseSuggestionResult {
            release_branch: "release/2.x".to_string(),
            bead_id: String::new(),
            backports_included: 2,
            success: false,
            errors: vec!["bd create failed".to_string()],
        };

        assert!(!result.success);
        assert_eq!(result.errors.len(), 1);
        assert_eq!(result.errors[0], "bd create failed");
    }
}
